import type { EasingName } from '../board/settings'

export const EASINGS: Record<EasingName, (t: number) => number> = {
  linear: (t) => t,
  easeInOutSine: (t) => -(Math.cos(Math.PI * t) - 1) / 2,
  easeInOutCubic: (t) => (t < 0.5 ? 4 * t * t * t : 1 - Math.pow(-2 * t + 2, 3) / 2),
  easeInOutQuint: (t) => (t < 0.5 ? 16 * t ** 5 : 1 - Math.pow(-2 * t + 2, 5) / 2),
  easeOutExpo: (t) => (t === 1 ? 1 : 1 - Math.pow(2, -10 * t)),
  easeOutBack: (t) => {
    const c1 = 1.70158
    const c3 = c1 + 1
    return 1 + c3 * Math.pow(t - 1, 3) + c1 * Math.pow(t - 1, 2)
  },
  anticipate: (t) => {
    const s = 1.4
    return t < 0.5
      ? (Math.pow(2 * t, 2) * ((s + 1) * 2 * t - s)) / 2
      : (Math.pow(2 * t - 2, 2) * ((s + 1) * (t * 2 - 2) + s) + 2) / 2
  },
}

export const EASING_LABELS: Record<EasingName, string> = {
  linear: 'Lineal',
  easeInOutSine: 'Suave (seno)',
  easeInOutCubic: 'Cinemático',
  easeInOutQuint: 'Dramático',
  easeOutExpo: 'Frenado rápido',
  easeOutBack: 'Rebote',
  anticipate: 'Anticipación',
}

export const clamp01 = (v: number) => Math.max(0, Math.min(1, v))
export const lerp = (a: number, b: number, t: number) => a + (b - a) * t
